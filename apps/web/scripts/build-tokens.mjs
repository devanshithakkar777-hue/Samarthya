// Single source of truth for design tokens: design/tokens.json.
// Generates app/tokens.css and fails if any declared text/background pair misses its contrast target.
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("../design/tokens.json", import.meta.url), "utf8"));

const lin = (c) => { c /= 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
const lum = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return 0.2126 * lin((n >> 16) & 255) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255);
};
export const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

let failed = 0;
for (const [fg, bg, min] of t.textPairs) {
  const r = ratio(t.color[fg], t.color[bg]);
  const ok = r >= min;
  if (!ok) failed++;
  console.log(`${ok ? "ok  " : "FAIL"} ${fg} on ${bg}: ${r.toFixed(2)} (needs ${min})`);
}
for (const [fg, bg] of t.forbiddenTextPairs) {
  const r = ratio(t.color[fg], t.color[bg]);
  console.log(`note ${fg} on ${bg} is ${r.toFixed(2)}: never use as text${r >= 4.5 ? " (unexpectedly passes)" : ""}`);
}

const lines = ["/* generated by scripts/build-tokens.mjs from design/tokens.json; do not edit */", "@theme {"];
for (const [k, v] of Object.entries(t.color)) lines.push(`  --color-${k}: ${v};`);
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v};`);
for (const [k, v] of Object.entries(t.motion)) lines.push(`  --motion-${k}: ${v};`);
lines.push("}");
writeFileSync(new URL("../app/tokens.css", import.meta.url), lines.join("\n") + "\n");

if (failed) { console.error(`\n${failed} contrast pair(s) below target`); process.exit(1); }
console.log("\nall declared pairs meet their contrast targets; wrote app/tokens.css");
